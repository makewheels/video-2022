"""Ordinary comment rows and public read capabilities, independent of storage and HTTP."""

from typing import Protocol


class CommentReads(Protocol):
    def video_exists(self, video_id: str) -> bool: ...
    def count_top(self, video_id: str) -> int: ...
    def top(self, video_id: str, skip: int, limit: int, sort_by: str) -> tuple[dict, ...]: ...
    def replies(self, parent_id: str, skip: int, limit: int) -> tuple[dict, ...]: ...
    def count_all(self, video_id: str) -> int: ...
