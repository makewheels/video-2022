"""Comment mutations and counters, without storage-specific IDs or transactions in business rules."""

from typing import Protocol


class CommentStore(Protocol):
    def video_exists(self, video_id: str) -> bool: ...
    def video_owner(self, video_id: str) -> str | None: ...
    def comment(self, comment_id: str) -> dict | None: ...
    def create_comment(self, document: dict) -> str: ...
    def all_replies(self, parent_id: str) -> tuple[dict, ...]: ...
    def increment_replies(self, parent_id: str, delta: int) -> None: ...
    def increment_video_comments(self, video_id: str, delta: int) -> None: ...
    def remove_comment(self, comment_id: str) -> None: ...
    def remove_replies(self, parent_id: str) -> None: ...
    def remove_likes(self, comment_id: str) -> None: ...
    def find_like(self, comment_id: str, user_id: str | None) -> dict | None: ...
    def create_like(self, document: dict) -> str: ...
    def remove_like(self, like_id: str) -> None: ...
    def increment_likes(self, comment_id: str, delta: int) -> None: ...
