"""Ordinary LOCAL registration values and capabilities; completion belongs to its caller."""

from dataclasses import dataclass
from datetime import datetime
from typing import Protocol

from video_serverless.ports.output_validation import OutputObjects


@dataclass(frozen=True)
class StoredOutput:
    key: str
    size: int
    etag: str | None
    storage_class: str | None
    upload_time: datetime | None


class OutputSidecar(Protocol):
    def integer(self, name: str, *, primitive: bool = False) -> int | None: ...
    def text(self, name: str) -> str | None: ...


class RegistrationObjects(OutputObjects, Protocol):
    def read_sidecar(self, key: str) -> OutputSidecar | None: ...
    def signed_playlist(self, key: str) -> str: ...
    def metadata(self, key: str) -> StoredOutput | None: ...
    def list_outputs(self, prefix: str) -> tuple[StoredOutput, ...]: ...


class RegistrationStore(Protocol):
    def video(self, video_id: str) -> dict | None: ...
    def file_by_key(self, key: str) -> dict | None: ...
    def segment(self, transcode_id: str, index: int) -> dict | None: ...
    def segments(self, transcode_id: str) -> list[dict]: ...
    def save_file(self, document: dict) -> None: ...
    def insert_segments(self, documents: list[dict]) -> None: ...
    def save_transcode(self, document: dict) -> None: ...
