"""Legacy notification reads and narrow read-state writes, without creating new notifications."""

from typing import Protocol


class NotificationStore(Protocol):
    def page(self, user_id: str | None, skip: int, limit: int) -> tuple[dict, ...]: ...
    def count(self, user_id: str | None) -> int: ...
    def count_unread(self, user_id: str | None) -> int: ...
    def mark_read(self, user_id: str | None, notification_id: str | None) -> None: ...
    def mark_all_read(self, user_id: str | None) -> None: ...
