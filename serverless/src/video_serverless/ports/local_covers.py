"""Ordinary local-cover registration capabilities; no media or provider SDK types."""

from datetime import datetime
from typing import Protocol

from video_serverless.ports.avatars import UploadCredentials


class LocalCoverStore(Protocol):
    def video_exists(self, video_id: str) -> bool: ...
    def user_exists(self, user_id: str) -> bool: ...
    def video(self, video_id: str) -> dict | None: ...
    def cover(self, cover_id: str) -> dict | None: ...
    def file(self, file_id: str) -> dict | None: ...
    def save_video(self, document: dict) -> None: ...
    def save_cover(self, document: dict) -> None: ...
    def save_file(self, document: dict) -> None: ...


class CoverIds(Protocol):
    def long_id(self, prefix: str) -> str: ...


class CoverClock(Protocol):
    def __call__(self) -> datetime: ...


class CoverUploads(Protocol):
    def upload_credentials(self, key: str) -> UploadCredentials | None: ...
