"""Local lane registration storage, without external media work."""

from typing import Protocol


class LocalTranscodeStore(Protocol):
    def video_exists(self, video_id: str) -> bool: ...
    def user_exists(self, user_id: str) -> bool: ...
    def video(self, video_id: str) -> dict | None: ...
    def file(self, file_id: str) -> dict | None: ...
    def transcode(self, transcode_id: str) -> dict | None: ...
    def save_video(self, document: dict) -> None: ...
    def save_transcode(self, document: dict) -> None: ...
